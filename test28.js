/* 오늘을 붙박이로 고정해 두면 시험이 날짜에 흔들리지 않는다 */
const 오늘 = new VMDate();
function 날(전) { const d = new VMDate(오늘.getTime()); d.setDate(d.getDate() - 전); return d; }
function ymd(전) {
  const d = 날(전), p = n => String(n).padStart(2, '0');
  return d.getFullYear() + '-' + p(d.getMonth() + 1) + '-' + p(d.getDate());
}

